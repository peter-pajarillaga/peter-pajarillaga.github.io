/* Draggable project carousel. Uses ONLY existing .explorer-card elements. */
document.addEventListener('DOMContentLoaded', () => {
  const rail = document.getElementById('projectRail');
  if (!rail) return;
  const cards = Array.from(rail.querySelectorAll('.explorer-card[data-project]'));
  if (!cards.length) return;
  const prev = document.getElementById('projectPrev');
  const next = document.getElementById('projectNext');
  const count = cards.length;
  const step = 360 / count;
  const reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  let angle = 0, startAngle = 0, startX = 0, lastX = 0;
  let pointerId = null, moved = false, suppressClick = false;
  const norm = degrees => ((degrees + 180) % 360 + 360) % 360 - 180;
  const nearest = () => Math.round(angle / step) * step;
  function render() {
    const width = rail.clientWidth;
    const cardWidth = cards[0].getBoundingClientRect().width || 205;
    const radius = Math.max(70, Math.min(width * .32, 230));
    const depth = Math.max(40, Math.min(width * .12, 90));
    cards.forEach((card, i) => {
      const a = norm(i * step - angle);
      const radians = a * Math.PI / 180;
      const x = Math.sin(radians) * radius;
      const z = Math.cos(radians) * depth;
      const scale = .76 + .24 * (Math.cos(radians) + 1) / 2;
      const t = `translateX(${x.toFixed(2)}px) translateZ(${z.toFixed(2)}px) rotateY(${(-a*.42).toFixed(2)}deg) scale(${scale.toFixed(3)})`;
      card.style.setProperty('--carousel-transform', t);
      card.style.transform = t;
      card.style.zIndex = String(Math.round(z + 100));
      card.style.opacity = String(.56 + .44 * (Math.cos(radians) + 1) / 2);
    });
  }
  function settle(activate = true) {
    angle = nearest();
    rail.classList.remove('is-dragging');
    render();
    if (activate) {
      const index = ((Math.round(angle / step) % count) + count) % count;
      // The existing project-viewer handler updates the screenshot and description.
      cards[index].click();
    }
  }
  function rotate(delta) { angle = nearest() + delta * step; settle(); }
  prev?.addEventListener('click', () => rotate(-1));
  next?.addEventListener('click', () => rotate(1));
  rail.addEventListener('pointerdown', e => {
    if (e.button !== 0 && e.pointerType === 'mouse') return;
    pointerId = e.pointerId;
    startX = lastX = e.clientX;
    startAngle = angle;
    moved = false;
    rail.setPointerCapture(e.pointerId);
    rail.classList.add('is-dragging');
  });
  rail.addEventListener('pointermove', e => {
    if (pointerId !== e.pointerId) return;
    lastX = e.clientX;
    if (Math.abs(lastX - startX) > 7) moved = true;
    if (!moved) return;
    angle = startAngle - (lastX - startX) / Math.max(180, rail.clientWidth) * 240;
    render();
  });
  function finish(e) {
    if (pointerId !== e.pointerId) return;
    pointerId = null;
    if (moved) {
      suppressClick = true;
      settle();
      // Only suppress the browser's click generated by this drag.
      setTimeout(() => { suppressClick = false; }, 80);
    } else {
      rail.classList.remove('is-dragging');
    }
  }
  rail.addEventListener('pointerup', finish);
  rail.addEventListener('pointercancel', finish);
  rail.addEventListener('lostpointercapture', e => { if (pointerId === e.pointerId) finish(e); });
  rail.addEventListener('click', e => {
    if (suppressClick && e.isTrusted) { e.preventDefault(); e.stopImmediatePropagation(); }
  }, true);
  cards.forEach((card, i) => card.addEventListener('click', e => {
    if (!e.isTrusted) return; // programmatic click already handled by existing viewer
    const current = Math.round(angle / step);
    const difference = ((i - current) % count + count) % count;
    angle = (current + (difference > count / 2 ? difference - count : difference)) * step;
    render();
  }));
  rail.addEventListener('keydown', e => {
    if (e.key === 'ArrowLeft') { e.preventDefault(); rotate(-1); }
    if (e.key === 'ArrowRight') { e.preventDefault(); rotate(1); }
  });
  window.addEventListener('resize', render);
  render();
});
